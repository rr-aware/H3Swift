#!/usr/bin/env python3
"""Regenerate the private C symbol namespace from a standard CH3 build (macOS)."""
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent.parent
subprocess.run(["swift", "build", "--target", "CH3"], cwd=root, check=True)
bin_path = Path(subprocess.check_output(["swift", "build", "--show-bin-path"], cwd=root, text=True).strip())
symbols = set()
for source in sorted((root / "src/h3lib/lib").glob("*.c")):
    obj = bin_path / "CH3.build/src/h3lib/lib" / (source.name + ".o")
    output = subprocess.check_output(["nm", "-g", "-U", str(obj)], text=True)
    for line in output.splitlines():
        fields = line.split()
        if len(fields) == 3:
            # Mach-O prefixes C symbols with one underscore.
            assert fields[2].startswith("_"), fields[2]
            symbols.add(fields[2][1:])
assert symbols, "No symbols found"
header = (
    "// Generated by scripts/update-extended-namespace.py; do not edit by hand.\n"
    "// Every external engine symbol must be isolated from the standard CH3 target.\n"
    "#pragma once\n"
)
header += "".join(f"#define {name} h3ext_private_{name}\n" for name in sorted(symbols))
(root / "bindings/extended/namespace.h").write_text(header)
